public class Operator {
    public static void main(String[] args) {
        int a = 10;
        int b = 10;
        System.out.println("Hello World");
        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);
        System.out.println(a%b);
        
        int c = 50;
        c+=10;
        System.out.println(c);
        c-=5;
        System.out.println(c);
    }
}
